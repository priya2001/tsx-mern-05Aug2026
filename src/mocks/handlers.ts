const responseForPage = (page: number): PeopleApiResponse => {
  if (page === 1) {
    return {
      count: 12,
      next: buildPeopleUrl(2),
      previous: null,
      results: pageOneCharacters,
    };
  }

  if (page === 2) {
    return {
      count: 12,
      next: null,
      previous: buildPeopleUrl(1),
      results: pageTwoCharacters,
    };
  }

  return {
    count: 0,
    next: null,
    previous: null,
    results: [],
  };
};

